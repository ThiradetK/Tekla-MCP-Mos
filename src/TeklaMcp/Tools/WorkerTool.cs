using System;
using System.Linq;
using Newtonsoft.Json.Linq;
using TeklaMcp.Core;
using TeklaMcp.Tekla;

namespace TeklaMcp.Tools
{
    /// <summary>READ tool that maps its arguments to one worker operation and summarizes the result.</summary>
    internal sealed class WorkerTool : IReadTool
    {
        private readonly TeklaWorker _worker;
        private readonly string _op;
        private readonly Func<JObject, JObject> _mapArgs;
        private readonly Func<JObject, string> _summary;

        public WorkerTool(TeklaWorker worker, string name, string title, string description, JObject schema,
                          string op, Func<JObject, JObject> mapArgs, Func<JObject, string> summary)
        {
            _worker = worker; Name = name; Title = title; Description = description; InputSchema = schema;
            _op = op; _mapArgs = mapArgs ?? (a => a); _summary = summary;
        }

        public string Name { get; }
        public string Title { get; }
        public string Description { get; }
        public ToolLevel Level => ToolLevel.Read;
        public JObject InputSchema { get; }

        public ToolResult Execute(JObject args)
        {
            JObject r = _worker.Call(_op, _mapArgs(args));
            return ToolResult.Ok(_summary(r), r);
        }
    }

    /// <summary>Shared object-filter arguments for find / quantity / export tools.</summary>
    internal static class ObjectFilter
    {
        public static JObject Properties() => new JObject
        {
            ["types"] = SchemaBuilder.Array(SchemaBuilder.String("Object type", TeklaText.ObjectTypes),
                "Object types to include. Default [\"part\"] (all parts). \"rebar\" includes bars generated by rebar sets. Ignored types are filtered when 'selection' or 'bbox' is used."),
            ["profile"] = SchemaBuilder.String("Profile filter, * and ? wildcards, case-insensitive (e.g. \"H*\", \"WF400X200*\"). For rebar this is the bar size."),
            ["material"] = SchemaBuilder.String("Material/grade filter with wildcards (e.g. \"SS400\", \"C4*\", \"SD40\")."),
            ["name"] = SchemaBuilder.String("Name filter with wildcards."),
            ["class"] = SchemaBuilder.String("Class filter with wildcards (class is text, e.g. \"6\")."),
            ["phase"] = SchemaBuilder.Integer("Phase number.", 0),
            ["uda"] = SchemaBuilder.Array(SchemaBuilder.Object(new JObject
            {
                ["name"] = SchemaBuilder.String("User-defined attribute name"),
                ["value"] = SchemaBuilder.String("Value with wildcards")
            }, "name", "value"), "User-defined attribute filters (all must match)."),
            ["selection"] = SchemaBuilder.Boolean("true = only the objects currently selected in Tekla."),
            ["bbox"] = SchemaBuilder.Object(new JObject
            {
                ["min"] = SchemaBuilder.Array(SchemaBuilder.Number("mm"), "[x, y, z] minimum corner, global mm"),
                ["max"] = SchemaBuilder.Array(SchemaBuilder.Number("mm"), "[x, y, z] maximum corner, global mm")
            }, "min", "max")
        };

        /// <summary>Copies filter arguments into the worker "query" format.</summary>
        public static JObject ToWorker(JObject a)
        {
            var w = new JObject();
            if (a["types"] != null) w["types"] = a["types"].DeepClone();
            if ((bool?)a["selection"] == true) w["selection"] = true;
            if (a["bbox"] is JObject bb)
            {
                foreach (var k in new[] { "min", "max" })
                    if (!(bb[k] is JArray p) || p.Count != 3) throw new TeklaException("invalid_arguments", "bbox." + k + " must be [x, y, z] in mm.");
                w["bbox"] = bb.DeepClone();
            }
            var f = new JObject();
            foreach (var k in new[] { "profile", "material", "name", "class", "phase", "uda" })
                if (a[k] != null) f[k] = a[k].DeepClone();
            w["filter"] = f;
            return w;
        }

        public static JObject Merge(JObject a, JObject b)
        {
            var r = (JObject)a.DeepClone();
            foreach (var p in b.Properties()) r[p.Name] = p.Value.DeepClone();
            return r;
        }

        public static string Guids(JToken arr) => arr == null ? "" : string.Join(", ", arr.Values<string>().Take(3)) + (arr.Count() > 3 ? ", ..." : "");
    }
}
